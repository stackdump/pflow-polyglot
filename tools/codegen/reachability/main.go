// Command reachability emits the full reachable state space of model.json as
// parity/reachability.golden.
//
//	reachability -out parity/reachability.golden model.json
//
// parity/trace.golden pins one linearization. It cannot express what this net
// actually is: a concurrent system whose opening marking enables three
// transitions, and which admits twenty distinct maximal firing sequences that
// all happen to end in the same place. A single trace is consistent with a net
// that has no concurrency at all, so it cannot distinguish "the implementations
// agree" from "the implementations agree about one path through a machine none
// of them has explored".
//
// The proof forms in Go, Rust, Python, JavaScript, Bash and Lean each compute
// this space internally, assert 1-safety and the unique {Payment} deadlock, and
// then throw it away. Six independent model-checkers that never compare notes
// are six programs trusted on their own say-so; emitting the space once, as a
// shared artifact, is what lets them be checked against each other instead.
//
// Output is deterministic: markings sorted by their canonical rendering,
// enabled transitions sorted by name. See FORMS.md § canonical scheduling
// policy.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"sort"

	"github.com/stackdump/pflow-polyglot/tools/codegen/internal/petri"
)

func main() {
	out := flag.String("out", "", "output file (default: stdout)")
	trace := flag.Bool("trace", false, "emit the canonical trace derived from the state space, not the space itself")
	flag.Parse()

	if flag.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "usage: reachability [-out <file>] [-trace] <model.json>")
		os.Exit(2)
	}

	model, err := petri.Load(flag.Arg(0))
	if err != nil {
		fmt.Fprintln(os.Stderr, "reachability:", err)
		os.Exit(1)
	}

	space, err := explore(model)
	if err != nil {
		fmt.Fprintln(os.Stderr, "reachability:", err)
		os.Exit(1)
	}

	rendered := render(model, space)
	if *trace {
		rendered = renderTrace(space)
	}

	if *out == "" {
		os.Stdout.Write(rendered)
		return
	}
	if err := os.WriteFile(*out, rendered, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "reachability:", err)
		os.Exit(1)
	}
}

// state is one reachable marking with everything the artifact records about it.
type state struct {
	key     string   // canonical sorted rendering, e.g. "Cup,Payment"
	enabled []string // transition names, sorted
	targets []string // successor marking keys, aligned with enabled
}

type stateSpace struct {
	states    []state // sorted by key
	terminals []string
	initial   string // key of the initial marking; states is sorted, so this is not states[0]
	edges     int
}

// explore walks the reachable space breadth-first from the initial marking.
//
// No bound is needed to terminate: the net is 1-safe, so a marking is a subset
// of the places and the space is bounded by 2^|places|. That 1-safety holds is
// a claim the proof forms check rather than assume; here it is enforced, since
// the canonical enablement rule refuses to produce into a marked place.
func explore(model petri.Model) (stateSpace, error) {
	initial := model.InitialMarking()
	seen := map[string]petri.Marking{initial.Key(): initial}
	frontier := []petri.Marking{initial}
	space := stateSpace{initial: initial.Key()}

	for len(frontier) > 0 {
		marking := frontier[0]
		frontier = frontier[1:]

		s := state{key: marking.Key()}
		for _, name := range model.EnabledIn(marking) {
			t, ok := model.ByName(name)
			if !ok {
				return space, fmt.Errorf("enabled transition %q is not in the model", name)
			}
			next := petri.Fire(marking, t)
			s.enabled = append(s.enabled, name)
			s.targets = append(s.targets, next.Key())
			space.edges++

			if _, ok := seen[next.Key()]; !ok {
				seen[next.Key()] = next
				frontier = append(frontier, next)
			}
		}
		if len(s.enabled) == 0 {
			space.terminals = append(space.terminals, s.key)
		}
		space.states = append(space.states, s)
	}

	sort.Slice(space.states, func(i, j int) bool { return space.states[i].key < space.states[j].key })
	sort.Strings(space.terminals)
	return space, nil
}

func render(model petri.Model, space stateSpace) []byte {
	var b bytes.Buffer

	fmt.Fprintln(&b, "# Reachable state space of model.json under the canonical semantics in FORMS.md.")
	fmt.Fprintln(&b, "# Code generated by tools/codegen/reachability; DO NOT EDIT.")
	fmt.Fprintln(&b, "#")
	fmt.Fprintln(&b, "# Companion to parity/trace.golden, which pins one of the maximal firing")
	fmt.Fprintln(&b, "# sequences below. This file pins the machine that trace is a path through.")
	fmt.Fprintln(&b, "#")
	fmt.Fprintln(&b, "# marking     {place,place,...}, places sorted; {} is the empty marking")
	fmt.Fprintln(&b, "# enabled     one 'transition -> successor' per enabled transition, sorted by")
	fmt.Fprintln(&b, "#             transition name. The first is the one the canonical scheduling")
	fmt.Fprintln(&b, "#             policy fires; a marking with none is terminal.")
	fmt.Fprintln(&b, "")

	fmt.Fprintf(&b, "places      %s\n", joinNames(model.Places))
	var names []string
	for _, t := range model.Transitions {
		names = append(names, t.Name)
	}
	fmt.Fprintf(&b, "transitions %s\n", joinNames(names))
	fmt.Fprintf(&b, "initial     {%s}\n", model.InitialMarking().Key())
	fmt.Fprintln(&b, "")
	fmt.Fprintf(&b, "markings    %d\n", len(space.states))
	fmt.Fprintf(&b, "edges       %d\n", space.edges)
	fmt.Fprintf(&b, "terminals   %d\n", len(space.terminals))
	fmt.Fprintln(&b, "")

	for _, s := range space.states {
		fmt.Fprintf(&b, "marking {%s}\n", s.key)
		if len(s.enabled) == 0 {
			fmt.Fprintln(&b, "  terminal")
			continue
		}
		for i, name := range s.enabled {
			fmt.Fprintf(&b, "  %s -> {%s}\n", name, s.targets[i])
		}
	}

	fmt.Fprintln(&b, "")
	for _, t := range space.terminals {
		fmt.Fprintf(&b, "terminal {%s}\n", t)
	}

	return b.Bytes()
}

// renderTrace walks the state space under the canonical scheduling policy —
// from the initial marking, always taking the lexicographically-least enabled
// transition — and renders the result in trace.golden's format.
//
// This is what ties the two goldens together. reachability.golden describes the
// machine; trace.golden pins one path through it. Deriving the second from the
// first and diffing means neither can drift from the other silently: a change
// to the net that leaves the trace intact still moves the space, and a change
// to the policy moves the trace out from under the space.
func renderTrace(space stateSpace) []byte {
	byKey := map[string]state{}
	for _, s := range space.states {
		byKey[s.key] = s
	}

	var b bytes.Buffer
	// space.states[0] is sorted by key, so the walk must start from the
	// initial marking explicitly rather than from the first state.
	current := space.initial
	for step := 1; ; step++ {
		s, ok := byKey[current]
		if !ok || len(s.enabled) == 0 {
			return b.Bytes()
		}
		// enabled is sorted, so index 0 is the policy's choice.
		fmt.Fprintf(&b, "Step #%d: %s => %s\n", step, s.enabled[0], s.targets[0])
		current = s.targets[0]
	}
}

func joinNames(names []string) string {
	out := ""
	for i, n := range names {
		if i > 0 {
			out += ","
		}
		out += n
	}
	return out
}
